type ManualPremiumEntry = {
  id: number;
  slug: string;
  title: string;
  originalTitle: string;
  type: ContentType;
  year: string;
  rating: number;
  genres: string[];
  countries: string[];
  imdbId: string;
  duration: string;
  studio: string;
  budget?: string;
  director?: string;
  creator?: string;
  franchise?: string;
  cast: CastMember[];
  description: string;
  longDescription: string;
};
function getTmdbPoster(input: { imdbId?: string; title: string; originalTitle?: string; year?: string; type?: string }) {
  const params = new URLSearchParams();
  if (input.imdbId) params.set("imdbId", input.imdbId);
  params.set("title", input.title);
  if (input.originalTitle) params.set("originalTitle", input.originalTitle);
  if (input.year) params.set("year", input.year);
  if (input.type) params.set("type", input.type);
  params.set("quality", "high");
  params.set("v", "manual-premium-2");
  return `/api/tmdb/poster?${params.toString()}`;
}
function createCollapseImdbPlayer(entry: Pick<ManualPremiumEntry, "slug" | "imdbId">): PlayerProvider[] {
  return [
    {
      id: `collapse-imdb-${entry.imdbId}`,
      name: "Основной",
      type: "collapse",
      provider: "collapse",
      embedUrl: `https://api.ortified.ws/embed/imdb/${entry.imdbId}?sharing=false&episodesOpen=false`,
      contentKind: "imdb",
      contentType: "imdb",
      contentId: entry.imdbId,
    },
  ];
}
function createFacts(entry: ManualPremiumEntry): MovieFact[] {
  return [
    { label: "Страна", value: entry.countries.join(", ") },
    { label: "Длительность", value: entry.duration },
    entry.director ? { label: "Режиссёр", value: entry.director } : undefined,
    entry.creator ? { label: "Создатель", value: entry.creator } : undefined,
    { label: "Студия", value: entry.studio },
    entry.budget ? { label: "Бюджет", value: entry.budget } : undefined,
    entry.franchise ? { label: "Франшиза", value: entry.franchise } : undefined,
    { label: "Настроение", value: getMood(entry) },
    { label: "Темы", value: getThemes(entry) },
  ].filter(Boolean) as MovieFact[];
}
function getMood(entry: ManualPremiumEntry) {
  if (entry.genres.includes("Ужасы")) return "Мрачно, напряжённо, атмосферно";
  if (entry.genres.includes("Мультфильм")) return "Ярко, быстро, семейно";
  if (entry.genres.includes("Фантастика")) return "Технологично, масштабно, с интригой";
  if (entry.genres.includes("Технологии")) return "Нервно, современно, параноидально";
  return "Динамично, цепко, без лишней воды";
}
function getThemes(entry: ManualPremiumEntry) {
  if (entry.franchise) return `${entry.franchise}, выбор, доверие, последствия`;
  if (entry.genres.includes("Технологии")) return "цифровой след, контроль, личность";
  if (entry.genres.includes("Фантастика")) return "будущее, система, человеческий выбор";
  return "семья, команда, испытание";
}
