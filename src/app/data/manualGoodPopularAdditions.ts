function createManualGoodPopularPosterFallback(movie: ManualGoodPopularEntry) {
  return getTmdbPoster({
    tmdbId: movie.tmdbId,
    imdbId: movie.imdbId,
    title: movie.title,
    originalTitle: movie.originalTitle,
    year: movie.year,
    type: movie.type,
  });
}

function createManualGoodPopularFacts(movie: ManualGoodPopularEntry): MovieFact[] {
  const creatorLabel = movie.type === "Сериал" ? "Создатели" : "Режиссёр";
  const creatorValue = movie.creators || movie.director;

  return [
    { label: "Год", value: movie.year },
    { label: "Тип", value: movie.type },
    { label: "Страна", value: movie.countries?.join(", ") || "" },
    { label: "Длительность", value: movie.duration },
    creatorValue ? { label: creatorLabel, value: creatorValue } : null,
    movie.studio ? { label: "Студия", value: movie.studio } : null,
    { label: "Настроение", value: movie.mood },
    { label: "Темы", value: movie.themes },
  ].filter((fact): fact is MovieFact => Boolean(fact && fact.value));
}

