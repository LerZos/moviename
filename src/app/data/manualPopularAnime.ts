function createCollapseAnimePlayer(entry: Pick<ManualAnimeEntry, "imdbId">): PlayerProvider[] {
  return [
    {
      id: `collapse-imdb-${entry.imdbId}`,
      name: "Основной",
      type: "collapse",
      provider: "collapse",
      embedUrl: `https://api.ortified.ws/embed/imdb/${entry.imdbId}?sharing=false&episodesOpen=false`,
      contentKind: "imdb",
      contentType: "imdb",
      contentId: entry.imdbId,
    },
  ];
}
function createFacts(entry: ManualAnimeEntry): MovieFact[] {
  return [
    { label: "Страна", value: entry.countries.join(", ") },
    { label: "Длительность", value: "около 24 мин / серия" },
    { label: "Создатель", value: entry.creator },
    { label: "Студия", value: entry.studio },
    { label: "Формат", value: "аниме-сериал" },
    { label: "Настроение", value: getMood(entry) },
    { label: "Темы", value: getThemes(entry) },
  ];
}
function getMood(entry: ManualAnimeEntry) {
  if (entry.genres.includes("Спорт")) return "Азартно, командно, вдохновляюще";
  if (entry.genres.includes("Драма")) return "Эмоционально, напряжённо, атмосферно";
  if (entry.genres.includes("Комедия")) return "Бодро, смешно, легко включается";
  return "Энергично, феймово, с сильной динамикой";
}
function getThemes(entry: ManualAnimeEntry) {
  if (entry.genres.includes("Спорт")) return "команда, рост, соперничество";
  if (entry.genres.includes("Фантастика")) return "время, выбор, последствия";
  if (entry.genres.includes("Фэнтези")) return "сила, путь героя, испытания";
  return "дружба, характер, цена силы";
}
