export function getRelatedSeoCollections(collection: SeoCollection, limit = 6) {
  const currentItems = new Set(collection.itemSlugs);

  return seoCollections
    .filter((item) => item.slug !== collection.slug)
    .map((item) => {
      const sharedItems = item.itemSlugs.filter((slug) => currentItems.has(slug)).length;
      const sameGroup = item.group === collection.group ? 2 : 0;

      return {
        collection: item,
        score: sharedItems * 3 + sameGroup,
      };
    })
    .sort((first, second) => second.score - first.score)
    .slice(0, limit)
    .map((item) => item.collection);
}

export function getSeoCollectionGroups() {
  return Array.from(new Set(seoCollections.map((collection) => collection.group))).map(
    (group) => ({
      group,
      collections: seoCollections.filter((collection) => collection.group === group),
    }),
  );
}
