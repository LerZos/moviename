export function getSeoCollection(slug: string) {
  return collectionMap.get(slug);
}

export function getSeoCollectionItems(collection: SeoCollection): Movie[] {
  const usedSlugs = new Set<string>();

  return collection.itemSlugs
    .filter((slug) => {
      if (usedSlugs.has(slug)) {
        return false;
      }

      usedSlugs.add(slug);
      return true;
    })
    .map((slug) => movieMap.get(slug))
    .filter((movie): movie is Movie => Boolean(movie));
}

